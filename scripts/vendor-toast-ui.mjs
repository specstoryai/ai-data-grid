// Generates packages/cells/vendor/toast-ui/{editor.js,toastui-editor.css} from the pinned
// @toast-ui/editor 3.2.2 devDependency of packages/cells (SPST-48).
//
// editor.js is Toast UI's dist/esm/index.js with patches P1-P5 applied (see
// packages/cells/vendor/toast-ui/README.md). Every anchor is exact and has an expected
// match count, and both inputs are pinned by sha256, so any drift fails loudly instead of
// producing a silently different file.
//
// Usage:
//   node scripts/vendor-toast-ui.mjs          regenerate the vendored files
//   node scripts/vendor-toast-ui.mjs --check  exit non-zero if the committed files differ
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CELLS = join(ROOT, "packages/cells");
const OUT_DIR = join(CELLS, "vendor/toast-ui");

const INPUT_VERSION = "3.2.2";
const INPUT_JS_SHA256 = "ff71315070f5151b638307fc66faa7e22c479a5e8e3fd566442475958401e524";
const INPUT_CSS_SHA256 = "c0ceb967b8c97038dccaa2a35c2222ec35b53a0022febbb6a22715c23ead9211";

const sha256 = s => createHash("sha256").update(s).digest("hex");

function fail(message) {
    console.error(`vendor-toast-ui: ${message}`);
    process.exit(1);
}

// The package's exports map doesn't expose ./package.json, so resolve its CJS entry
// (dist/toastui-editor.js) from the cells package and walk up from there.
function locateInput() {
    const require = createRequire(join(CELLS, "package.json"));
    let entry;
    try {
        entry = require.resolve("@toast-ui/editor");
    } catch {
        fail("@toast-ui/editor is not installed; run `npm ci` first");
    }
    const distDir = dirname(entry);
    const manifest = JSON.parse(readFileSync(join(distDir, "..", "package.json"), "utf8"));
    if (manifest.name !== "@toast-ui/editor" || manifest.version !== INPUT_VERSION) {
        fail(`expected @toast-ui/editor@${INPUT_VERSION}, found ${manifest.name}@${manifest.version}`);
    }
    return distDir;
}

function readPinned(file, expected) {
    const text = readFileSync(file, "utf8");
    const actual = sha256(text);
    if (actual !== expected) fail(`${file}: sha256 ${actual}, expected ${expected}`);
    return text;
}

// Replace an exact anchor that must occur exactly `expected` times.
function replaceExact(src, from, to, expected, label) {
    const count = src.split(from).length - 1;
    if (count !== expected) fail(`${label}: expected ${expected} match(es), found ${count}`);
    return src.split(from).join(to);
}

function replaceRegex(src, re, to, expected, label) {
    const count = (src.match(re) ?? []).length;
    if (count !== expected) fail(`${label}: expected ${expected} match(es), found ${count}`);
    return src.replace(re, to);
}

function patch(src) {
    // H0: generated-file header (comment only).
    src =
        "/* ai-data-grid: GENERATED by scripts/vendor-toast-ui.mjs from Toast UI Editor's\n" +
        " * dist/esm/index.js with patches P1-P5. Do not edit by hand; see README.md. */\n" +
        src;

    // P1: remove the embedded DOMPurify 2.3.3 and use a private instance of the external
    // `dompurify` package instead. Sanitizing fails closed if DOMPurify is unsupported.
    const bannerStart = "/*! @license DOMPurify 2.3.3 |";
    const instanceLine = "var purify = createDOMPurify();\n";
    if (src.split(bannerStart).length !== 2 || src.split(instanceLine).length !== 2) {
        fail("P1: embedded DOMPurify anchors not found exactly once");
    }
    const start = src.indexOf(bannerStart);
    const end = src.indexOf(instanceLine) + instanceLine.length;
    if (end <= start) fail("P1: embedded DOMPurify anchors out of order");
    src =
        src.slice(0, start) +
        "/* ai-data-grid patch P1: the embedded DOMPurify copy is removed. Toast UI sanitizes through a\n" +
        " * private instance of the external `dompurify` package, so an app's setConfig/addHook on the\n" +
        " * default instance can't weaken it. */\n" +
        "var purify = DOMPurify();\n" +
        src.slice(end);
    src = replaceExact(
        src,
        "import { undo, redo, history, undoDepth } from 'prosemirror-history';\n",
        "import { undo, redo, history, undoDepth } from 'prosemirror-history';\n" +
            "/* ai-data-grid patch P1: external DOMPurify */\n" +
            "import DOMPurify from 'dompurify';\n",
        1,
        "P1 import"
    );
    src = replaceExact(
        src,
        "function sanitizeHTML(html, options) {\n    return purify.sanitize(",
        "function sanitizeHTML(html, options) {\n" +
            "    /* ai-data-grid patch P1: fail closed; DOMPurify 3 returns its input unchanged when unsupported */\n" +
            "    if (!purify.isSupported) {\n" +
            "        throw new Error('ai-data-grid: DOMPurify is not supported in this environment; refusing to render unsanitized HTML');\n" +
            "    }\n" +
            "    return purify.sanitize(",
        1,
        "P1 fail-closed guard"
    );

    // P2: sanitize pasted HTML before any other processing. The Office list conversion
    // assigns it to innerHTML of an element in the live document, and the parse rules copy
    // data-raw-html into node attributes. ProseMirror runs this for dropped HTML too (P5).
    src = replaceExact(
        src,
        "    html = convertMsoTableToCompletedTable(html);\n    if (isFromMso(html)) {",
        "    html = convertMsoTableToCompletedTable(html);\n" +
            "    /* ai-data-grid patch P2: sanitize pasted HTML; data-raw-html is Toast UI-internal */\n" +
            "    html = sanitizeHTML(html, { FORBID_ATTR: ['data-raw-html'] });\n" +
            "    if (isFromMso(html)) {",
        1,
        "P2 paste"
    );

    // P3: rawHTML becomes the tag name that toDOM and the Markdown writer emit, so only
    // accept the value Toast UI itself sets (the element's own, allowlisted tag name).
    src = replaceRegex(
        src,
        /\b(\w+)\.getAttribute\('data-raw-html'\)/g,
        "safeRawHTMLTag($1) /* ai-data-grid patch P3 */",
        13,
        "P3 rawHTML reads"
    );
    src = replaceExact(
        src,
        "                    acc[attrName] = includes(['rawHTML', 'extended'], attrName)\n" +
            "                        ? attrValue\n",
        "                    acc[attrName] = includes(['rawHTML', 'extended'], attrName)\n" +
            "                        ? (attrName === 'rawHTML' ? safeRawHTMLTag(dom) /* ai-data-grid patch P3 */ : attrValue)\n",
        1,
        "P3 table cell rawHTML"
    );

    // P4: WYSIWYG link href and image src render only URLs DOMPurify accepts. The model
    // value is untouched, so saved Markdown doesn't change.
    src = replaceExact(
        src,
        "href: escapeXml$1(attrs.linkUrl)",
        "href: escapeXml$1(safeURL('a', 'href', attrs.linkUrl)) /* ai-data-grid patch P4 */",
        1,
        "P4 link toDOM"
    );
    src = replaceExact(
        src,
        "src: escapeXml$1(attrs.imageUrl)",
        "src: escapeXml$1(safeURL('img', 'src', attrs.imageUrl)) /* ai-data-grid patch P4 */",
        1,
        "P4 image toDOM"
    );
    src = replaceExact(
        src,
        "        image.src = imageUrl;\n",
        "        image.src = safeURL('img', 'src', imageUrl); /* ai-data-grid patch P4 */\n",
        1,
        "P4 ImageView"
    );

    // P5: Toast UI's dropImage plugin reported every drop as handled but only prevented the
    // default for image files, so ProseMirror skipped every other drop and the browser
    // inserted the dropped HTML natively (Firefox runs its event handlers). Report only a
    // handled image drop, so ProseMirror parses the rest through transformPastedHTML (P2),
    // and prevent every drop that reaches the editor's root unprevented. That covers drops
    // ProseMirror declines and node views that stop events (code blocks, images).
    src = replaceExact(
        src,
        "                            return true;\n" +
            "                        });\n" +
            "                    }\n" +
            "                    return true;\n" +
            "                },\n" +
            "            },\n" +
            "        },\n" +
            "    });\n" +
            "}\n",
        "                            return true;\n" +
            "                        });\n" +
            "                    }\n" +
            "                    /* ai-data-grid patch P5: only a handled image drop is handled here; ProseMirror parses\n" +
            "                     * every other drop through transformPastedHTML (P2) */\n" +
            "                    return ev.defaultPrevented;\n" +
            "                },\n" +
            "            },\n" +
            "        },\n" +
            "        /* ai-data-grid patch P5: no drop is left to the browser's native insertion. This listener\n" +
            "         * runs after ProseMirror's own (plugin views are created after its input handlers), so it\n" +
            "         * only matters for drops ProseMirror declined or never saw (node views that stop events). */\n" +
            "        view: function (editorView) {\n" +
            "            var preventNativeDrop = function (ev) { ev.preventDefault(); };\n" +
            "            editorView.dom.addEventListener('drop', preventNativeDrop);\n" +
            "            return {\n" +
            "                destroy: function () { editorView.dom.removeEventListener('drop', preventNativeDrop); },\n" +
            "            };\n" +
            "        },\n" +
            "    });\n" +
            "}\n",
        1,
        "P5 dropImage"
    );

    // Helpers for P3 and P4, defined right after sanitizeHTML.
    src = replaceExact(
        src,
        "\nfunction getChildrenHTML(node, typeName) {",
        "\n/* ai-data-grid patch P3: tag names Toast UI itself writes to data-raw-html */\n" +
            "var RAW_HTML_TAGS = ['b', 'strong', 'i', 'em', 's', 'del', 'code', 'a', 'img', 'hr', 'br', 'pre', 'ul', 'ol', 'li',\n" +
            "    'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'blockquote', 'table', 'thead', 'tbody', 'tr', 'th', 'td'];\n" +
            "function safeRawHTMLTag(dom) {\n" +
            "    var tag = dom.getAttribute('data-raw-html');\n" +
            "    return tag && tag === dom.nodeName.toLowerCase() && includes(RAW_HTML_TAGS, tag) ? tag : null;\n" +
            "}\n" +
            "/* ai-data-grid patch P4: URL guard for WYSIWYG link and image rendering */\n" +
            "function safeURL(tag, attr, url) {\n" +
            "    return url && purify.isSupported && purify.isValidAttribute(tag, attr, url) ? url : '';\n" +
            "}\n" +
            "\nfunction getChildrenHTML(node, typeName) {",
        1,
        "P3/P4 helpers"
    );

    for (const forbidden of ["createDOMPurify", "@license DOMPurify", "DOMPurify.version = '2.3.3'"]) {
        if (src.includes(forbidden)) fail(`output still contains ${JSON.stringify(forbidden)}`);
    }
    return src;
}

const distDir = locateInput();
const outputs = [
    { file: join(OUT_DIR, "editor.js"), content: patch(readPinned(join(distDir, "esm/index.js"), INPUT_JS_SHA256)) },
    {
        file: join(OUT_DIR, "toastui-editor.css"),
        content: readPinned(join(distDir, "toastui-editor.css"), INPUT_CSS_SHA256),
    },
];

const check = process.argv.includes("--check");
let stale = 0;
for (const { file, content } of outputs) {
    const rel = relative(ROOT, file);
    if (check) {
        const committed = existsSync(file) ? readFileSync(file, "utf8") : undefined;
        if (committed !== content) {
            console.error(`vendor-toast-ui: ${rel} is out of date; run node scripts/vendor-toast-ui.mjs`);
            stale++;
        } else {
            console.log(`ok ${rel} sha256 ${sha256(content)}`);
        }
    } else {
        writeFileSync(file, content);
        console.log(`wrote ${rel} sha256 ${sha256(content)}`);
    }
}
if (stale > 0) process.exit(1);
